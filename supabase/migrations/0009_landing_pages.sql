  on public.global_sections for delete
  to authenticated
  using (public.is_cms_admin());

-- ── 4. redirects — minimal seed of a future standalone Redirect Manager ───
-- Auto-populated whenever a landing page's slug or root_alias changes, so old
-- links/backlinks/bookmarks don't silently 404. Same table would back a full
-- Redirect Manager module later — no throwaway work if that gets built.
create table if not exists public.redirects (
  id               bigint generated by default as identity primary key,
  source_path      text not null unique,
  destination_path text not null,
  status_code      int not null default 308,
  reason           text,
  landing_page_id  uuid references public.landing_pages (id) on delete set null,
  created_at       timestamptz not null default now()
);

alter table public.redirects enable row level security;

-- Public read: resolved on every unmatched public route, not just admin edits.
